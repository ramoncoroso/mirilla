/** Formato de _locales/<idioma>/messages.json. */
export function toMessagesJson(messages: Record<string, string>): string {
  const out: Record<string, { message: string }> = {};
  for (const [key, message] of Object.entries(messages)) out[key] = { message };
  return JSON.stringify(out, null, 2);
}
